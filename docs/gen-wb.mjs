#!/usr/bin/env node
/**
 * Regenerate docs/wb.md from the real `wb tools --json` output and the wb exit-code mapping
 * (packages/wb/src/main.js `exitCodeFor`), formatted with the repo's prettier config so the file
 * is stable under `prettier --write`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { Codes } from '../packages/protocol/src/errors.js';
import { exitCodeFor } from '../packages/wb/src/main.js';
import { exitStatus } from '../packages/wb/src/commands.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');

/** Path of the generated reference. */
export const WB_DOC = path.join(here, 'wb.md');

/** Path of the wb entry point whose `tools --json` output the reference is built from. */
export const WB_MAIN = path.join(root, 'packages', 'wb', 'src', 'main.js');

/** The parsed output of `wb tools --json`. @returns {{schema: number, tools: {name: string, summary: string, usage: string}[]}} */
export function wbToolsJson() {
  const out = execFileSync(process.execPath, [WB_MAIN, 'tools', '--json'], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  const doc = JSON.parse(out);
  if (!doc || !Array.isArray(doc.tools)) throw new Error('wb tools --json printed no tools array');
  return doc;
}

const cell = (s) => String(s).replaceAll('|', '\\|');

function exitRows() {
  const byStatus = new Map();
  for (const code of Object.values(Codes)) {
    const status = exitCodeFor(code);
    byStatus.set(status, [...(byStatus.get(status) ?? []), code]);
  }
  const meaning = {
    1: 'internal error, and every code not mapped to another status',
    2: 'usage: bad arguments, unknown command or method, unparsable input',
    3: 'not found',
    4: 'denied or unavailable: policy refusal, quarantined sandbox, no control channel',
    5: 'timeout',
  };
  return [...byStatus.keys()]
    .sort((a, b) => a - b)
    .map(
      (s) =>
        `| ${s} | ${meaning[s] ?? ''} | ${byStatus
          .get(s)
          .map((c) => `\`${c}\``)
          .join(', ')} |`,
    );
}

/** The complete docs/wb.md text. @returns {Promise<string>} */
export async function renderWbDoc() {
  const { tools } = wbToolsJson();
  const lines = [
    '# wb reference',
    '',
    '<!-- Generated by docs/gen-wb.mjs from `wb tools --json`; do not edit by hand. -->',
    '',
    '`wb` is the agent command inside a sandbox (`/opt/workbox/bin/wb`, on `PATH`). It talks only to',
    'the in-box runner on `/run/workbox/runner.sock`; brokered subcommands are relayed to the host.',
    'Every subcommand accepts `--help` and `--json`. With `--json`, a command prints one JSON value',
    'on stdout, and a failure prints `{"error": {"code", "message", "data"?}}` there instead.',
    'Diagnostics go to stderr. `wb help <command>` and `wb <command> --help` print the usage below.',
    '',
    '## Commands',
    '',
    '| Command | Summary | Usage |',
    '| --- | --- | --- |',
    ...tools.map((t) => `| \`${t.name}\` | ${cell(t.summary)} | \`${cell(t.usage)}\` |`),
    '',
    '## Exit codes',
    '',
    'A failed wb call exits with the status its protocol error code maps to (`exitCodeFor` in',
    'packages/wb/src/main.js):',
    '',
    '| Exit | Meaning | Error codes |',
    '| --- | --- | --- |',
    '| 0 | success | |',
    ...exitRows(),
    '',
    '`wb run`, `wb secret exec` and `wb session attach` on a finished session exit with the',
    "wrapped command's own status instead: its exit code, or 128 + the signal number when it died",
    `by a signal (SIGTERM gives ${exitStatus(null, 'SIGTERM')}, SIGKILL gives ${exitStatus(null, 'SIGKILL')}).`,
    '',
  ];
  const options = (await resolveConfig(WB_DOC)) ?? {};
  return format(lines.join('\n'), { ...options, filepath: WB_DOC });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  fs.writeFileSync(WB_DOC, await renderWbDoc());
  console.log('docs/wb.md regenerated');
}
